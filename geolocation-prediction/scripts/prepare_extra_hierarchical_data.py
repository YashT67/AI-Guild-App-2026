import os
import pandas as pd
import numpy as np
import torch

def latlon_to_cartesian(lat, lon):
    """Convert latitude and longitude to 3D Cartesian coordinates on a unit sphere."""
    lat_rad = np.radians(lat)
    lon_rad = np.radians(lon)
    x = np.cos(lat_rad) * np.cos(lon_rad)
    y = np.cos(lat_rad) * np.sin(lon_rad)
    z = np.sin(lat_rad)
    return np.column_stack((x, y, z))

def main():
    base_dir = r"C:\Users\Yash T\Desktop\geoguessr\geolocation-prediction"
    extra_dir = os.path.join(base_dir, "extra_training_dataset")
    cluster_dir = os.path.join(base_dir, "training_dataset", "noised_dataset", "hierarchical_clusters")
    
    csv_path = os.path.join(extra_dir, "coordinates.csv")
    out_csv_path = os.path.join(extra_dir, "extra_hierarchical_clustered.csv")
    
    if os.path.exists(out_csv_path):
        print(f"--> Found {out_csv_path}. Skipping preprocessing.")
        return
    
    print("Loading 210k extra coordinates...")
    df = pd.read_csv(csv_path)
    df['id'] = df['id'].astype(str)
    
    # Scan physical folders to map image locations
    print("Scanning physical folders (00 to 04) to map image locations...")
    id_to_folder = {}
    for folder in ['00', '01', '02', '03', '04']:
        folder_path = os.path.join(extra_dir, "images", folder)
        if not os.path.exists(folder_path):
            continue
        for f in os.listdir(folder_path):
            if f.endswith('.jpg'):
                id_to_folder[f.replace('.jpg', '')] = folder
                
    df['folder'] = df['id'].map(id_to_folder)
    df = df.dropna(subset=['folder']).reset_index(drop=True)
    print(f"Matched {len(df)} images to physical files.")
    
    # Convert all coordinates to 3D Cartesian
    print("Converting to 3D Cartesian...")
    xyz = latlon_to_cartesian(df['latitude'].values, df['longitude'].values)
    
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    xyz_tensor = torch.tensor(xyz, dtype=torch.float32, device=device)
    
    # Load the SAME centroids generated by prepare_hierarchical_data.py
    # This ensures both datasets share identical cluster definitions
    hierarchies = [
        {'k': 4, 'name': 'macro', 'col': 'cluster_macro_4'},
        {'k': 36, 'name': 'meso', 'col': 'cluster_meso_36'},
        {'k': 216, 'name': 'micro', 'col': 'cluster_micro_216'}
    ]
    
    chunk_size = 10000
    
    for h in hierarchies:
        centroids_path = os.path.join(cluster_dir, f"centroids_{h['name']}_{h['k']}.csv")
        if not os.path.exists(centroids_path):
            print(f"ERROR: {centroids_path} not found! Run prepare_hierarchical_data.py first.")
            return
        
        centroids_df = pd.read_csv(centroids_path)
        centroid_coords = centroids_df[['x', 'y', 'z']].values
        cluster_ids = centroids_df['cluster_id'].values
        
        centroid_tensor = torch.tensor(centroid_coords, dtype=torch.float32, device=device)
        
        print(f"Assigning {len(df)} images to {h['k']} {h['name']} clusters...")
        all_assigned = []
        
        for i in range(0, len(xyz_tensor), chunk_size):
            chunk = xyz_tensor[i:i+chunk_size]
            # Euclidean distance on unit sphere (equivalent to angular distance for nearest)
            dist_sq = torch.sum((chunk.unsqueeze(1) - centroid_tensor.unsqueeze(0))**2, dim=2)
            closest_idxs = torch.argmin(dist_sq, dim=1).cpu().numpy()
            all_assigned.extend([cluster_ids[idx] for idx in closest_idxs])
        
        df[h['col']] = all_assigned
        print(f"  -> Done. Distribution: min={pd.Series(all_assigned).value_counts().min()}, max={pd.Series(all_assigned).value_counts().max()}")
    
    # Standardize columns
    df = df.rename(columns={'id': 'image_id'})
    df = df[['image_id', 'latitude', 'longitude', 'folder', 'cluster_macro_4', 'cluster_meso_36', 'cluster_micro_216']]
    
    print(f"\nSaving to {out_csv_path}...")
    df.to_csv(out_csv_path, index=False)
    print(f"SUCCESS! {len(df)} images mapped to hierarchical clusters.")

if __name__ == "__main__":
    main()
